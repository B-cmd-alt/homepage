// Evolve a society headless and save its notebooks as the page's starting population.
//
//   node sim/save.js            writes ../start.js
//
// The page loads start.js so it opens on an evolved society, not on empty notebooks,
// and keeps learning from there.
'use strict';
const fs = require('fs');
const path = require('path');
const World = require('../world.js');

const SEED = 7, HOURS = 3, DT = 1 / 20;
const w = new World({ seed: SEED });
for (let i = 0; i < HOURS * 3600 / DT; i++) w.step(DT);

const b = w.beliefs();
const out = {
  note: `Saved by sim/save.js: seed ${SEED}, ${HOURS} simulated hours, reward '${w.cfg.reward}'.`,
  lifetime: Math.round(w.lifeSum / w.deaths),
  points: w.save(),
};
fs.writeFileSync(path.join(__dirname, '..', 'start.js'),
  '// Generated by sim/save.js. Do not edit by hand.\nwindow.LIGHT_START = ' + JSON.stringify(out) + ';\n');
console.log(`saved ${out.points.length} notebooks · mean generation ${b.generation.toFixed(0)} · approach alone ${b.approachAlone.toFixed(2)} · give fine ${b.giveFine.toFixed(2)} · mean lifetime ${out.lifetime} s`);
